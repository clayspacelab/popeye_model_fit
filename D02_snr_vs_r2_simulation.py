"""
D02_snr_vs_r2_simulation.py
============================
Task-band Fractional Spectral Power vs pRF Fit R² — Simulation Validation

OVERVIEW
--------
This script tests whether a data-quality measure derived purely from the
raw fMRI timeseries can predict how well the pRF model fits a given voxel.
It computes "Task-band Fractional Spectral Power" (TFSP) per voxel, then
correlates that against R² from S02_run_simulation_fit.py.

MEASURE: Task-band Fractional Spectral Power (TFSP)
------------------------------------------------------
TFSP is a stimulus-aware extension of fALFF (Zou et al. 2008, Brain Research):

    TFSP = Σ |X(f)| for f in [f_min, f_max]
           ────────────────────────────────────
           Σ |X(f)| for all f > f_drift

where |X(f)| is the FFT amplitude at frequency f.

Key design decisions vs. naïve relative power:

  1. AMPLITUDE not power: We use |FFT|, not |FFT|², following the fALFF
     convention. Power (|FFT|²) over-weights large-amplitude frequency bins
     and is less robust to spectral spikes or physiological artifacts. The
     amplitude form gives a more uniform weighting across the spectrum.

  2. STIMULUS-DERIVED band [f_min, f_max]: The frequency band is not
     hardcoded to a resting-state convention (0.01–0.1 Hz). Instead, it is
     computed from the stimulus design — specifically the bar sweep cycle
     period, which sets the fundamental task frequency. The band spans from
     the Nyquist-limited fundamental down to its first harmonic, adapting
     automatically to any experiment design. For a typical bar sweep with
     cycle period ~25 s this resolves to roughly 0.008–0.08 Hz; for a fast
     event-related design the upper bound would shift higher.

  3. DRIFT FLOOR f_drift: Low-frequency scanner drift (< f_drift) is
     excluded from both numerator and denominator. This prevents drifty
     voxels from artificially inflating the measure. f_drift defaults to
     1 / (scan_duration / 2) — i.e., frequencies with periods longer than
     half the scan — but can be overridden.

WHY TFSP PREDICTS R² (SIMULATION CONTEXT)
------------------------------------------
In S01, voxels are generated by a deterministic CSS forward model (HRF
convolved with the stimulus response). The bar sweep signal concentrates
power in the low-frequency band matching the sweep periodicity. Additive
noise is broadband (white). Therefore:

    High signal amplitude → high TFSP → pRF model fits well → high R²

In real data the same logic holds: task-locked BOLD responses concentrate
energy in the task band; thermal, physiological, and motion noise are
broadband or at higher frequencies (cardiac ~1 Hz, respiratory ~0.3 Hz).

INPUTS
------
    Simulation/simulatedVoxels.pkl  — generated by S01_simulate_prf.py
    Simulation/popeyeFit/RF_ss5_[fg]Fit_popeye_Ns{Ns}.npy — from S02

OUTPUTS (saved to Simulation/figures/testing_snr/)
-------
    tfsp_vs_r2_{tag}.png           — scatter + regression + marginal hists
    tfsp_summary_panel_{tag}.png   — summary panel (scatter | TFSP hist | R2 hist)

USAGE
-----
    python D02_snr_vs_r2_simulation.py [--grid-size Ns]

    Examples:
        python D02_snr_vs_r2_simulation.py
        python D02_snr_vs_r2_simulation.py --grid-size 100
"""

import os
