def save_metrics(results, save_path, skip_final_fit, bin_medians):
    """Persist the sweep metrics as a .npz for downstream inspection."""
    Ns_vals = np.array([r['Ns'] for r in results])
    payload = {
        'Ns': Ns_vals,
        'n_grid_points': np.array([r['n_grid_points'] for r in results]),
        'grid_prep_time': np.array([r['grid_prep_time'] for r in results]),
        'grid_fit_time': np.array([r['grid_fit_time'] for r in results]),
        'final_fit_time': np.array([r['final_fit_time'] for r in results]),
        'grid_mean_r2': np.array([r['grid']['mean_r2'] for r in results]),
        'n_grid_values': np.array(N_GRID_VALUES),
        # TFSP-binned R²: rows = Ns, cols = TFSP decile (bin_medians labels cols).
        'tfsp_bin_medians': np.asarray(bin_medians),
        'grid_r2_by_bin': np.array([r['grid']['r2_by_bin'] for r in results]),
    }
    for name, _ in CORR_PARAMS:
        payload[f'grid_corr_{name}'] = np.array([r['grid']['corr'][name] for r in results])
        if not skip_final_fit:
            payload[f'final_corr_{name}'] = np.array([r['final']['corr'][name] for r in results])
    if not skip_final_fit:
        payload['final_mean_r2'] = np.array([r['final']['mean_r2'] for r in results])
        payload['final_r2_by_bin'] = np.array([r['final']['r2_by_bin'] for r in results])

    np.savez(save_path, **payload)
    print(f'Sweep metrics saved to {save_path}')


# Ground truth is loaded once and shared across all Ns (module-level so the
# per-Ns fit helper can reference it without re-threading it through every call).
trueFit_data_global = None


def main():
    args = parse_args()
    codeStartTime = time.perf_counter()

    params = dict(DEFAULT_PARAMS)
    params['subjID'] = 'JC'
    p, _ = set_paths(params['subjID'], data_format='volumetric')

    # ── Logging setup ──────────────────────────────────────────────────────────
    log_dir = os.path.join(p['pRF_data'], 'Simulation', 'logs')
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    log_path = os.path.join(log_dir, f'S03_{timestamp}.log')
    logger = TeeLogger(log_path)
    sys.stdout = logger
    sys.stderr = logger
    # ───────────────────────────────────────────────────────────────────────────

    try:
        _run(args, codeStartTime, p, params)
    except Exception:
        traceback.print_exc()
        raise
    finally:
        print(f'\nLog saved to: {log_path}')
        logger.close()


def _run(args, codeStartTime, p, params):
    global trueFit_data_global
    set_dark_theme()

    # Load simulation data (shared across the whole sweep).
    print('Loading simulated data...')
    scan_data, trueFit_data = load_simulation_data(p, args.n_voxels)
    trueFit_data_global = trueFit_data
    nvoxs = scan_data.shape[0]

    print('=== Grid-size Sweep (S03) ===')
    print(f'Run started: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}')
    print(f'Mode:        {"plot-only (rebuild figures from saved fits)" if args.plot_only else "fit + plot"}')
    print(f'N voxels:    {nvoxs}')
    print(f'Grid sizes:  {args.grid_sizes}')
    print(f'n-grid:      {N_GRID_VALUES} ({len(N_GRID_VALUES)} values)')
    if not args.plot_only:
        print(f'GPU:         {"enabled" if args.use_gpu else "disabled"}')
        print(f'Prefetch:    {"disabled" if args.no_prefetch else "enabled (depth 1)"}')
        print(f'Final fit:   {"skipped" if args.skip_final_fit else "enabled"}')
        if not args.skip_final_fit:
            print(f'  n_iter:    {args.n_iter}')
            print(f'  lr:        {args.lr}')
            print(f'  sub_batch: {args.sub_batch if args.sub_batch is not None else "auto"}')
    print()

    # Detrend once.
    timeseries_data = remove_trend(scan_data, method='all')
    indices = [(0, 0, i) for i in range(nvoxs)]

    # Load stimulus once (identical across Ns).
    bar, _ = load_stimuli(p)
    bar = bar[:, :, 0:201]
    bar = np.flip(bar, axis=0)
    func_img = nib.load(p['pRF_ss5'])
    stimulus = VisualStimulus(
        bar.astype('int16'),
        params['viewingDistance'],
        params['screenWidth'],
        params['scaleFactor'],
        float(func_img.header['pixdim'][4]),
        params['dtype'],
    )

    # TFSP (SNR) per voxel, computed once from the detrended data (independent of
    # Ns). Voxels are binned by TFSP decile so R² can be tracked per SNR bin.
    print('Computing TFSP (SNR) per voxel and assigning TFSP bins...')
    tfsp, _, _, _ = compute_tfsp(timeseries_data, tr=params['tr_length'],
                                 sweep_period_s=TFSP_SWEEP_PERIOD_S)
    bin_labels, bin_medians = compute_tfsp_bins(tfsp, N_TFSP_BINS)

    # All S03 outputs live under dedicated S03 subfolders of the usual dirs.
    fit_dir = os.path.join(p['pRF_data'], 'Simulation', 'popeyeFit', 'S03')
    os.makedirs(fit_dir, exist_ok=True)
    fig_dir = os.path.join(p['pRF_data'], 'Simulation', 'figures', 'S03')
    os.makedirs(fig_dir, exist_ok=True)

    grid_sizes = list(args.grid_sizes)
    effective_skip = args.skip_final_fit

    if args.plot_only:
        # Rebuild results from previously saved fits — no fitting.
        results, effective_skip = build_results_from_saved(
            grid_sizes, fit_dir, stimulus, trueFit_data, args.skip_final_fit,
            bin_labels, N_TFSP_BINS)
        if not results:
            print('[plot-only] No saved fits found for the requested Ns — nothing to plot.')
            return
    else:
        # Sweep. The CPU grid-prediction of the next Ns is overlapped with the GPU
        # fit of the current Ns (prefetch depth 1), since they use disjoint resources
        # (process Pool vs GPU) and grid predictions are independent of the fit.
        nTRs = timeseries_data.shape[1]
        results = []

        def _prep(Ns):
            return prepare_gridpreds(Ns, stimulus, p, nTRs)

        if args.no_prefetch or len(grid_sizes) <= 1:
            for Ns in grid_sizes:
                grid_space, param_width, grid_preds, prep_time = _prep(Ns)
                results.append(
                    fit_from_preds(Ns, grid_space, param_width, grid_preds, prep_time,
                                   stimulus, timeseries_data, indices, nvoxs,
                                   args.use_gpu, args.skip_final_fit, fit_dir,
                                   bin_labels, N_TFSP_BINS,
                                   n_iter=args.n_iter, lr=args.lr, sub_batch=args.sub_batch)
                )
        else:
            print(f'\nPrefetch enabled: overlapping next-Ns grid prediction with '
                  f'current-Ns GPU fit (depth 1).')
            with ThreadPoolExecutor(max_workers=1) as ex:
                fut = ex.submit(_prep, grid_sizes[0])
                for i, Ns in enumerate(grid_sizes):
                    grid_space, param_width, grid_preds, prep_time = fut.result()
                    # Kick off the next Ns's CPU prediction before we occupy the GPU.
                    if i + 1 < len(grid_sizes):
                        fut = ex.submit(_prep, grid_sizes[i + 1])
                    results.append(
                        fit_from_preds(Ns, grid_space, param_width, grid_preds, prep_time,
                                       stimulus, timeseries_data, indices, nvoxs,
                                       args.use_gpu, args.skip_final_fit, fit_dir,
                                       bin_labels, N_TFSP_BINS,
                                       n_iter=args.n_iter, lr=args.lr, sub_batch=args.sub_batch)
                    )

    plot_accuracy_vs_ns(results, os.path.join(fig_dir, 'accuracy_vs_Ns.png'),
                        effective_skip)
    plot_r2_vs_ns(results, os.path.join(fig_dir, 'r2_vs_Ns.png'),
                  effective_skip)
    plot_r2_by_tfsp_bin(results, os.path.join(fig_dir, 'r2_by_tfsp_bin_vs_Ns.png'),
                        effective_skip, bin_medians, N_TFSP_BINS)
    if args.plot_only:
        print('[plot-only] Runtime figure skipped — per-Ns timing is not persisted.')
    else:
        plot_runtime_vs_ns(results, os.path.join(fig_dir, 'runtime_vs_Ns.png'),
                           effective_skip)
    save_metrics(results, os.path.join(fig_dir, 'sweep_metrics.npz'),
                 effective_skip, bin_medians)

    codeEndTime = time.perf_counter()
    print_time(codeStartTime, codeEndTime,
               'Total plot-only rebuild' if args.plot_only else 'Total grid-size sweep')


if __name__ == '__main__':
    main()
