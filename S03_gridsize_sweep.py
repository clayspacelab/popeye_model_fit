def build_grid_space(stimulus, Ns):
    """Build the (x, y, sigma, n) grid space for a given Ns, using the fine n grid.

    Mirrors the grid construction in S02 but substitutes the 10-point n grid.
    Returns (grid_space, param_width).
    """
    x_grid = np.concatenate((
        np.linspace(-stimulus.deg_x0.max(), stimulus.deg_x0.max(), Ns // 2),
        np.geomspace(-stimulus.deg_x0.max(), -2 * stimulus.deg_x0.max(), Ns // 4),
        np.geomspace(stimulus.deg_x0.max(), 2 * stimulus.deg_x0.max(), Ns // 4),
    ))
    y_grid = np.concatenate((
        np.linspace(-stimulus.deg_y0.max(), stimulus.deg_y0.max(), Ns // 2),
        np.geomspace(-stimulus.deg_y0.max(), -2 * stimulus.deg_y0.max(), Ns // 4),
        np.geomspace(stimulus.deg_y0.max(), 2 * stimulus.deg_y0.max(), Ns // 4),
    ))
    s_grid = np.concatenate((
        np.linspace(0.1, 5, 3 * Ns // 4),
        np.geomspace(5, stimulus.deg_x0.max(), Ns // 4),
    ))
    n_grid = np.asarray(N_GRID_VALUES)

    grid_space_orig = list(product(x_grid, y_grid, s_grid, n_grid))
    grid_space = constraint_grids(grid_space_orig, stimulus)

    param_width = [np.mean(np.diff(x_grid)), np.mean(np.diff(y_grid)),
                   np.mean(np.diff(s_grid)), np.mean(np.diff(n_grid))]
    return grid_space, param_width


def circular_error_deg(theta_true, theta_fit):
    """Signed angular error (fit − true) wrapped to [−180°, 180°].

    Linear differences on polar angle are wrong across the 0↔2π boundary; the
    arctan2(sin, cos) trick maps the difference back onto the shortest arc.
    """
    d = np.asarray(theta_fit, dtype=float) - np.asarray(theta_true, dtype=float)
    return np.degrees(np.arctan2(np.sin(d), np.cos(d)))


def per_voxel_errors(trueFit_data, fitted_data):
    """Per-voxel error array for each ERROR_PARAMS entry.

    position → Euclidean RF-center distance (deg, ≥0)
    theta    → circular angular error (deg, signed, in [−180, 180])
    sigma, n → signed error (fit − true), so median bias is meaningful
    """
    t = np.asarray(trueFit_data, dtype=float)
    fdat = np.asarray(fitted_data, dtype=float)
    return {
        'position': np.hypot(fdat[:, 5] - t[:, 5], fdat[:, 6] - t[:, 6]),
        'theta': circular_error_deg(t[:, 0], fdat[:, 0]),
        'sigma': fdat[:, 3] - t[:, 3],
        'n': fdat[:, 4] - t[:, 4],
    }


def compute_metrics(trueFit_data, fitted_data):
    """Return (per-voxel error dict, mean model-fit R²).

    The error dict feeds every accuracy summary (MAE/RMSE/bias/IQR are derived
    at plot time so voxel-level spread is preserved). ``mean_r2`` is the model's
    own goodness-of-fit (col 1) — model quality, NOT parameter recovery.
    """
    errs = per_voxel_errors(trueFit_data, fitted_data)
    mean_r2 = float(np.nanmean(fitted_data[:, 1]))
    return errs, mean_r2


def _err_summary(err):
    """(MAE, RMSE, median-bias, |err| q25, |err| q75) over finite entries."""
    e = np.asarray(err, dtype=float)
    e = e[np.isfinite(e)]
    if e.size == 0:
        return (np.nan, np.nan, np.nan, np.nan, np.nan)
    ae = np.abs(e)
    return (float(np.mean(ae)), float(np.sqrt(np.mean(e ** 2))),
            float(np.median(e)), float(np.percentile(ae, 25)),
            float(np.percentile(ae, 75)))


def prepare_gridpreds(Ns, stimulus, p, nTRs):
    """CPU stage: build the grid space and load-or-generate its grid predictions.

    This is the only compute-heavy CPU step (`getGridPreds` uses a process Pool)
    and is independent of the GPU fit, so it can run for Ns=(k+1) while the GPU
    fits Ns=k. Returns (grid_space, param_width, grid_preds, prep_time).
    """
    t0 = time.perf_counter()
    grid_space, param_width = build_grid_space(stimulus, Ns)
    print(f'[Ns={Ns}] Grid space: {len(grid_space)} points '
          f'(n-grid resolution = {len(N_GRID_VALUES)})')

    gridfit_path = get_gridfit_path(p, Ns, n_res=len(N_GRID_VALUES))
    if os.path.exists(gridfit_path):
        print(f'[Ns={Ns}] Loading grid predictions from disk ({gridfit_path})')
        grid_preds = np.load(gridfit_path)
    else:
        print(f'[Ns={Ns}] Generating grid predictions ({gridfit_path})...')
        grid_preds = getGridPreds(grid_space, stimulus, gridfit_path, nTRs)
    prep_time = time.perf_counter() - t0
    print_time(t0, time.perf_counter(), f'[Ns={Ns}] Grid predictions')
    return grid_space, param_width, grid_preds, prep_time


