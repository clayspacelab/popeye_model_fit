    t_grid = time.perf_counter()
    grid_time = t_grid - t_pred
    print_time(t_pred, t_grid, f'[Ns={Ns}] Grid fit')

    result = {
        'Ns': Ns,
        'n_grid_points': len(grid_space),
        'grid_prep_time': prep_time,
        'grid_fit_time': grid_time,
        'grid': None,
        'final': None,
    }
    gfit_save_path = os.path.join(fit_dir, f'RF_ss5_gFit_popeye_Ns{Ns}.npy')
    np.save(gfit_save_path, RF_gFit[0, 0, :, :])
