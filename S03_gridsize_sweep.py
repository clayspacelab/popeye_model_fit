def get_s03_gridfit_path(p, Ns, n_res):
    """Grid-prediction cache path for the sweep (encodes Ns and n-grid resolution).

    Lives alongside the other caches in ``Stimuli/gridestims/``. The Ns + n-res
    encoding keeps it distinct from the default ``gridfit_{Ns}.npy`` caches.
    """
    gridestims_dir = os.path.join(p['stimuli_path'], 'gridestims')
    os.makedirs(gridestims_dir, exist_ok=True)
    return os.path.join(gridestims_dir, f'gridfit_Ns{Ns}_n{n_res}.npy')


def build_grid_space(stimulus, Ns):
    """Build the (x, y, sigma, n) grid space for a given Ns, using the fine n grid.

    Mirrors the grid construction in S02 but substitutes the 10-point n grid.
    Returns (grid_space, param_width).
    """
    x_grid = np.concatenate((
        np.linspace(-stimulus.deg_x0.max(), stimulus.deg_x0.max(), Ns // 2),
        np.geomspace(-stimulus.deg_x0.max(), -2 * stimulus.deg_x0.max(), Ns // 4),
        np.geomspace(stimulus.deg_x0.max(), 2 * stimulus.deg_x0.max(), Ns // 4),
    ))
    y_grid = np.concatenate((
        np.linspace(-stimulus.deg_y0.max(), stimulus.deg_y0.max(), Ns // 2),
        np.geomspace(-stimulus.deg_y0.max(), -2 * stimulus.deg_y0.max(), Ns // 4),
        np.geomspace(stimulus.deg_y0.max(), 2 * stimulus.deg_y0.max(), Ns // 4),
    ))
    s_grid = np.concatenate((
        np.linspace(0.1, 5, 3 * Ns // 4),
        np.geomspace(5, stimulus.deg_x0.max(), Ns // 4),
    ))
    n_grid = np.asarray(N_GRID_VALUES)

    grid_space_orig = list(product(x_grid, y_grid, s_grid, n_grid))
    grid_space = constraint_grids(grid_space_orig, stimulus)

    param_width = [np.mean(np.diff(x_grid)), np.mean(np.diff(y_grid)),
                   np.mean(np.diff(s_grid)), np.mean(np.diff(n_grid))]
    return grid_space, param_width


def safe_pearsonr(true_vals, fit_vals):
    """Pearson r over finite pairs; NaN if too few or degenerate."""
    true_vals = np.asarray(true_vals, dtype=float).flatten()
    fit_vals = np.asarray(fit_vals, dtype=float).flatten()
    mask = np.isfinite(true_vals) & np.isfinite(fit_vals)
    if mask.sum() < 3:
        return np.nan
    tv, fv = true_vals[mask], fit_vals[mask]
    if np.std(tv) == 0 or np.std(fv) == 0:
        return np.nan
    return stats.pearsonr(tv, fv)[0]


def compute_metrics(trueFit_data, fitted_data):
    """Return (dict of param->Pearson r vs ground truth, mean R²)."""
    corr = {name: safe_pearsonr(trueFit_data[:, idx], fitted_data[:, idx])
            for name, idx in CORR_PARAMS}
    mean_r2 = float(np.nanmean(fitted_data[:, 1]))
    return corr, mean_r2


def compute_tfsp_bins(tfsp, n_bins):
    """Assign voxels to quantile (decile) TFSP bins.

    Quantile bins give ~equal voxel counts per bin and are robust to the skewed
    TFSP distribution. Returns (bin_labels (N,) in [0, n_bins-1], bin_medians
    (n_bins,) median TFSP per bin; NaN for any empty bin).
    """
    tfsp = np.asarray(tfsp).flatten()
    edges = np.quantile(tfsp, np.linspace(0, 1, n_bins + 1))
    # Interior edges only → digitize yields labels 0..n_bins-1.
    bin_labels = np.clip(np.digitize(tfsp, edges[1:-1]), 0, n_bins - 1)
    bin_medians = np.array([
        np.median(tfsp[bin_labels == b]) if np.any(bin_labels == b) else np.nan
        for b in range(n_bins)
    ])
    return bin_labels, bin_medians


def compute_r2_by_bin(r2_vals, bin_labels, n_bins):
    """Mean R² within each TFSP bin: (n_bins,), NaN for empty bins."""
    r2_vals = np.asarray(r2_vals).flatten()
    out = np.full(n_bins, np.nan)
    for b in range(n_bins):
        mask = (bin_labels == b) & np.isfinite(r2_vals)
        if mask.any():
            out[b] = float(np.mean(r2_vals[mask]))
    return out


def prepare_gridpreds(Ns, stimulus, p, nTRs):
    """CPU stage: build the grid space and load-or-generate its grid predictions.

    This is the only compute-heavy CPU step (`getGridPreds` uses a process Pool)
    and is independent of the GPU fit, so it can run for Ns=(k+1) while the GPU
    fits Ns=k. Returns (grid_space, param_width, grid_preds, prep_time).
    """
    t0 = time.perf_counter()
    grid_space, param_width = build_grid_space(stimulus, Ns)
    print(f'[Ns={Ns}] Grid space: {len(grid_space)} points '
          f'(n-grid resolution = {len(N_GRID_VALUES)})')

    gridfit_path = get_s03_gridfit_path(p, Ns, len(N_GRID_VALUES))
    if os.path.exists(gridfit_path):
        print(f'[Ns={Ns}] Loading grid predictions from disk ({gridfit_path})')
        grid_preds = np.load(gridfit_path)
    else:
        print(f'[Ns={Ns}] Generating grid predictions ({gridfit_path})...')
        grid_preds = getGridPreds(grid_space, stimulus, gridfit_path, nTRs)
    prep_time = time.perf_counter() - t0
    print_time(t0, time.perf_counter(), f'[Ns={Ns}] Grid predictions')
    return grid_space, param_width, grid_preds, prep_time


def fit_from_preds(Ns, grid_space, param_width, grid_preds, prep_time,
                   stimulus, timeseries_data, indices, nvoxs, use_gpu,
                   skip_final_fit, fit_dir, bin_labels, n_bins,
                   n_iter=300, lr=0.005, sub_batch=None):
    """GPU stage: grid fit (+ optional final fit) from precomputed predictions.

    Runs on the main thread so all CuPy work stays on a single device context.
    Grid- and final-fit estimates are saved to ``fit_dir`` (the S03 subfolder).
    ``bin_labels`` assigns each voxel to a TFSP bin so per-bin mean R² is recorded.
    """
    print(f'\n{"="*70}\n=== Ns = {Ns} ===\n{"="*70}')

    # Grid fit.
    print('Starting grid fit...')
    t_pred = time.perf_counter()
    RF_gFit = np.empty((1, 1, nvoxs, 9))
    RF_gFit = get_grid_estims(grid_preds, grid_space, timeseries_data,
                              RF_gFit, indices, use_gpu=use_gpu)
    t_grid = time.perf_counter()
    grid_time = t_grid - t_pred
    print_time(t_pred, t_grid, f'[Ns={Ns}] Grid fit')

    result = {
        'Ns': Ns,
        'n_grid_points': len(grid_space),
        'grid_prep_time': prep_time,
        'grid_fit_time': grid_time,
        'grid': None,
        'final': None,
    }
    gfit_save_path = os.path.join(fit_dir, f'RF_ss5_gFit_popeye_Ns{Ns}.npy')
    np.save(gfit_save_path, RF_gFit[0, 0, :, :])
    print(f'[Ns={Ns}] Grid-fit estimates saved to {gfit_save_path}')

    grid_corr, grid_r2 = compute_metrics(trueFit_data_global, RF_gFit[0, 0, :, :])
    result['grid'] = {
        'corr': grid_corr, 'mean_r2': grid_r2,
        'r2_by_bin': compute_r2_by_bin(RF_gFit[0, 0, :, 1], bin_labels, n_bins),
    }

    # Final fit (optional).
    if not skip_final_fit:
        print('Starting final fit...')
        RF_fFit = np.empty((1, 1, nvoxs, 9))
        RF_fFit = get_final_estims(RF_gFit, param_width, timeseries_data,
                                   stimulus, RF_fFit, indices, use_gpu=use_gpu,
                                   n_iter=n_iter, lr=lr, sub_batch=sub_batch)
        RF_fFit = RF_fFit.reshape(1, 1, nvoxs, 9)
        t_final = time.perf_counter()
        result['final_fit_time'] = t_final - t_grid
        print_time(t_grid, t_final, f'[Ns={Ns}] Final fit')

        ffit_save_path = os.path.join(fit_dir, f'RF_ss5_fFit_popeye_Ns{Ns}.npy')
        np.save(ffit_save_path, RF_fFit[0, 0, :, :])
        print(f'[Ns={Ns}] Final-fit estimates saved to {ffit_save_path}')

        final_corr, final_r2 = compute_metrics(trueFit_data_global, RF_fFit[0, 0, :, :])
        result['final'] = {
            'corr': final_corr, 'mean_r2': final_r2,
            'r2_by_bin': compute_r2_by_bin(RF_fFit[0, 0, :, 1], bin_labels, n_bins),
        }
    else:
        result['final_fit_time'] = np.nan

    return result


def build_results_from_saved(grid_sizes, fit_dir, stimulus, trueFit_data,
                             skip_final_fit, bin_labels, n_bins):
    """Reconstruct sweep results from previously saved grid/final fit .npy files.

    Used by --plot-only when a run was interrupted before the in-memory plotting
    step. Recomputes accuracy/R² metrics against ground truth for each Ns whose
    fits are present; timing is unavailable (not persisted) and set to NaN.

    Returns (results, effective_skip) where effective_skip is True if no final
    fits were found (so downstream plots show grid only).
    """
    def gpath(Ns):
        return os.path.join(fit_dir, f'RF_ss5_gFit_popeye_Ns{Ns}.npy')

    def fpath(Ns):
        return os.path.join(fit_dir, f'RF_ss5_fFit_popeye_Ns{Ns}.npy')

    any_final = any(os.path.exists(fpath(Ns)) for Ns in grid_sizes)
    use_final = (not skip_final_fit) and any_final
    if (not skip_final_fit) and not any_final:
        print('[plot-only] No final-fit files found — plotting grid fit only.')

    results = []
    for Ns in grid_sizes:
        if not os.path.exists(gpath(Ns)):
            print(f'[plot-only] Ns={Ns}: no grid fit at {gpath(Ns)} — skipping')
            continue
        if use_final and not os.path.exists(fpath(Ns)):
            print(f'[plot-only] Ns={Ns}: final fit missing — skipping for consistency')
            continue

        gfit = np.load(gpath(Ns))
        n = min(len(trueFit_data), len(gfit))
        grid_space, _ = build_grid_space(stimulus, Ns)
        gc, gr2 = compute_metrics(trueFit_data[:n], gfit[:n])
        res = {
            'Ns': Ns,
            'n_grid_points': len(grid_space),
            'grid_prep_time': np.nan,
            'grid_fit_time': np.nan,
            'final_fit_time': np.nan,
            'grid': {'corr': gc, 'mean_r2': gr2,
                     'r2_by_bin': compute_r2_by_bin(gfit[:n, 1], bin_labels[:n], n_bins)},
            'final': None,
        }
        if use_final:
            ffit = np.load(fpath(Ns))
            m = min(len(trueFit_data), len(ffit))
            fc, fr2 = compute_metrics(trueFit_data[:m], ffit[:m])
            res['final'] = {'corr': fc, 'mean_r2': fr2,
                            'r2_by_bin': compute_r2_by_bin(ffit[:m, 1], bin_labels[:m], n_bins)}
        results.append(res)
        print(f'[plot-only] Ns={Ns}: loaded ({"grid+final" if use_final else "grid"})')

    return results, (not use_final)


def plot_accuracy_vs_ns(results, save_path, skip_final_fit):
    """One panel per correlated parameter: Pearson r vs Ns (grid & final)."""
    Ns_vals = [r['Ns'] for r in results]

    f, axs = plt.subplots(2, 3, figsize=(18, 10))
    axs = axs.flatten()
    for ax, (name, _) in zip(axs, CORR_PARAMS):
        grid_r = [r['grid']['corr'][name] for r in results]
        ax.plot(Ns_vals, grid_r, '-o', color='#00e5ff', linewidth=1.6,
                markersize=5, label='grid fit')
        if not skip_final_fit:
            final_r = [r['final']['corr'][name] for r in results]
            ax.plot(Ns_vals, final_r, '-s', color='#ff4081', linewidth=1.6,
                    markersize=5, label='final fit')
        ax.set_title(f'{name}: corr(fitted, ground truth) vs Ns')
        ax.set_xlabel('Grid size (Ns)')
        ax.set_ylabel('Pearson r')
        ax.grid(True, alpha=0.3)
        ax.legend(fontsize=9, framealpha=0.3)

    f.suptitle('Parameter recovery vs grid size', fontsize=15)
    plt.tight_layout()
    plt.savefig(save_path, dpi=300, bbox_inches='tight')
    plt.close(f)
    print(f'Accuracy-vs-Ns plot saved to {save_path}')


