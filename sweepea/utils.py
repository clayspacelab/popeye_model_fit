def make_trends(n_frames, n_dct, verbose=False):
    """
    Create cosine trends for detrending fMRI data.
    Adapted from Vista rmMakeTrends.m.

    Parameters
    ----------
    n_frames : int
        Number of frames in the scan.
    n_dct : int
        Maximum DCT order. The number of trends is 2 * n_dct + 1.
    verbose : bool, default=False
        Print the number of generated trends.

    Returns
    -------
    t : numpy.ndarray, shape (n_frames, 2 * n_dct + 1)
        Cosine trend matrix.
    nt : int
        Number of trends.
    dcid : int
        Zero-based column index of the DC component.
    """
    n_frames = int(n_frames)
    n_dct = int(n_dct)

    if n_frames < 1:
        raise ValueError("n_frames must be positive")
    if n_dct < 0:
        raise ValueError("n_dct must be nonnegative")

    # MATLAB linspace(0, 2*pi, n_frames), including the endpoint.
    tc = np.linspace(0.0, 2.0 * np.pi, n_frames)

    # Equivalent to MATLAB's 0:0.5:nDCT.
    frequencies = np.arange(0.0, n_dct + 0.5, 0.5)

    # Outer product: one column per cosine frequency.
    t = np.cos(tc[:, None] * frequencies[None, :])

    nt = t.shape[1]

    # # MATLAB's dcid would be 1; Python uses zero-based indexing.
    # dcid = 0

    if verbose:
        print(f"Removing {nt} trends from combined data.")

    return t #t, nt, dcid

def detrend_vista(signal, n_dct=1):
    """
    Detrend fMRI signal using cosine trends, similar to Vista's rmMakeTrends.

    Parameters
    ----------
    signal : numpy.ndarray, shape (n_voxels, n_timepoints)
        Input fMRI signal.
    n_dct (int, default=1):
        Maximum DCT order for detrending.

    Returns
    -------
    detrended_signal : numpy.ndarray, shape (n_voxels, n_timepoints)
        Detrended fMRI signal.
    """

    #compute trends
    n_frames = signal.shape[1]
    trends = make_trends(n_frames, n_dct)

    # Fit trends to the signal using least squares and remove them
    betas, *_ = lstsq(trends, signal.T)
    detrended_signal = signal - (trends @ betas).T
   
    return detrended_signal


def preprocess_signal(signal, detrend_method, **kwargs):
    """
    Detrend and normalize (z-score) fMRI signal.
    Note: z-scoring is required for the model fitting to work properly, so other normalization 
    methods are no longer supported.

    Parameters
    ----------
    signal : ndarray
        Input signal array. Last axis is time.
    detrend_method : str
        'detrend'                — scipy.signal.detrend (linear detrending by default)
        'detrend_vista'           — Detrending using cosine trends (Vista-style)
        None or 'none'             — No detrending
    kwargs : additional keyword arguments to pass to the detrending functions (if needed).

    Returns
    -------
    ndarray
        Processed signal.
    """
    if detrend_method == 'detrend':
        #signal_mean = np.mean(signal, axis=-1)[..., None]
        signal_detrend = detrend(signal, axis=-1, **kwargs) #+ signal_mean``
    elif detrend_method == 'detrend_vista':
        signal_detrend = detrend_vista(signal, **kwargs)
    elif detrend_method is None or detrend_method == 'none':
        signal_detrend = signal
    else:
        raise ValueError(f"Unknown detrend method: '{detrend_method}'")

    # Z-score normalization
    signal_normalized = zscore(signal_detrend, axis=-1)

    return signal_normalized


